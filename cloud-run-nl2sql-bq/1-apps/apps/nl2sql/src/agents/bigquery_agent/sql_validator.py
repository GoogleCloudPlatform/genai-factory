import logging
from typing import Any

import sqlglot
from google.adk.tools.base_tool import BaseTool
from google.adk.tools.tool_context import ToolContext
from sqlglot import exp
from sqlglot.errors import SqlglotError

from src import config

logger = logging.getLogger(__name__)

_BLOCKED_FUNCTIONS = frozenset({
    "external_query",
    "ai.generate_table",
    "ml.predict",
    "vector_search",
})


def validate_sql_query(
    sql: str,
    allowed_project: str | None,
    allowed_dataset: str | None,
) -> str | None:
  """Validates that a BigQuery SQL query is read-only and scoped to one dataset.

  Args:
    sql: The SQL string generated by the LLM.
    allowed_project: Allowed BigQuery data project ID (BQ_DATA_PROJECT_ID).
    allowed_dataset: Allowed BigQuery dataset ID (BQ_DATASET_ID).

  Returns:
    None if the SQL query is allowed, or an error message string if rejected.
  """
  if not allowed_project or not allowed_dataset:
    return ("BigQuery dataset allowlist (BQ_DATA_PROJECT_ID and BQ_DATASET_ID) "
            "is not configured.")

  if not sql or not sql.strip():
    return "Empty SQL query is not allowed."

  try:
    statements = sqlglot.parse(sql, read="bigquery")
  except SqlglotError as exc:
    return f"Failed to parse SQL query: {exc}"

  if len(statements) != 1 or statements[0] is None:
    return "Only a single read-only SELECT query is allowed."

  stmt = statements[0]
  if not isinstance(stmt, exp.Query):
    return "Only read-only SELECT queries are allowed."

  if any(stmt.find_all(exp.Command, exp.DDL, exp.DML)):
    return "DDL, DML, and administrative SQL commands are not allowed."

  for func in stmt.find_all(exp.Anonymous):
    if func.name.lower() in _BLOCKED_FUNCTIONS:
      return f"Function '{func.name}' is not allowed."

  cte_names = {cte.alias_or_name.lower() for cte in stmt.find_all(exp.CTE)}
  tables = list(stmt.find_all(exp.Table))

  for table in tables:
    catalog = table.catalog
    db = table.db
    name = table.name

    if ("information_schema" in name.lower() or
        "information_schema" in db.lower()):
      return "Querying INFORMATION_SCHEMA views is not allowed."

    if "*" in name or "." in name:
      return (
          f"Wildcard or non-standard table reference '{name}' is not allowed. "
          f"Use `{allowed_project}.{allowed_dataset}.<table>`.")

    if not catalog and not db:
      if name.lower() in cte_names:
        continue
      return (
          f"Unqualified table '{name}' is not allowed. "
          f"Use fully qualified `{allowed_project}.{allowed_dataset}.{name}`.")

    if catalog != allowed_project or db != allowed_dataset or not name:
      target = ".".join(part for part in (catalog, db, name) if part)
      return (f"Access to '{target}' is denied. Queries may only read tables "
              f"in `{allowed_project}.{allowed_dataset}`.")

  return None


def validate_sql_tool_call(
    tool: BaseTool,
    args: dict[str, Any],
    tool_context: ToolContext,
) -> dict[str, Any] | None:
  """ADK before_tool_callback enforcing dataset allowlist on execute_sql."""
  del tool_context
  if tool.name != "execute_sql":
    logger.warning("Blocked disallowed tool invocation: %s", tool.name)
    return {
        "status": "ERROR",
        "error_details": f"Tool '{tool.name}' is not permitted.",
    }

  query = args.get("query")
  if not isinstance(query, str):
    return {
        "status": "ERROR",
        "error_details": "Missing or invalid 'query' string argument.",
    }

  error = validate_sql_query(
      sql=query,
      allowed_project=config.BQ_DATA_PROJECT_ID,
      allowed_dataset=config.BQ_DATASET_ID,
  )
  if error:
    logger.warning("Blocked SQL query via before_tool_callback: %s | SQL: %s",
                   error, query)
    return {
        "status": "ERROR",
        "error_details": error,
    }

  return None
